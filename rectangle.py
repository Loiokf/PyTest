def area(a, b):
    """
    Вычисляет площадь прямоугольника по двум сторонам

    a (int): длина первой стороны
    b (int): длина второй стороны
    return (int): площадь прямоугольника

    Пример вызова:
        >>> area(3, 5)
        15
    """
    return a * b


def perimeter(a, b):
    """
    Вычисляет периметр прямоугольника по двум сторонам

    a (int): длина первой стороны
    b (int): длина второй стороны
    return (int): периметр прямоугольника

    Пример вызова:
        >>> perimeter(3, 5)
        16
    """
    return (a + b) * 2