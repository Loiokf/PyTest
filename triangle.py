def area(a, h):
    """
    Вычисляет площадь треугольника по стороне и высоте, проведённой к ней

    a (int): длина стороны треугольника
    h (int): высота, проведённая к стороне a
    return (float): площадь треугольника

    Пример вызова:
        >>> area(6, 4)
        12.0
    """
    return a * h / 2


def perimeter(a, b, c):
    """
    Вычисляет периметр треугольника по трём сторонам

    a (int): длина первой стороны
    b (int): длина второй стороны
    c (int): длина третьей стороны
    return (int): периметр треугольника

    Пример вызова:
        >>> perimeter(3, 4, 5)
        12
    """
    return a + b + c
